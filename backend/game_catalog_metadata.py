def estimated_duration_minutes(game_name: str) -> int:
    """도감에 새 게임이 추가되어도 추천이 중단되지 않도록 기본값을 둔다."""
    return GAME_DURATION_MINUTES.get(game_name, 45)


def format_duration(minutes: int) -> str:
    if minutes <= 20:
        return "약 20분"
    if minutes <= 30:
        return "약 30분"
    if minutes <= 45:
        return "약 45분"
    if minutes <= 60:
        return "약 1시간"
    if minutes <= 90:
        return "약 1시간 30분"
    return "약 2시간"
